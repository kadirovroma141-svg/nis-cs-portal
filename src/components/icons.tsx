type PhosphorProps = ComponentProps<typeof PCheck>;
export type IconProps = Omit<PhosphorProps, "weight"> & { weight?: IconWeight; strokeWidth?: number };
export type Icon = ComponentType<IconProps>;

function mk(P: ComponentType<PhosphorProps>, weight: IconWeight = "bold"): Icon {
  function I({ strokeWidth, weight: w, ...props }: IconProps) {
    void strokeWidth; // accepted for old call sites, not used by this set
    return <P weight={w ?? weight} {...props} />;
  }
  return I;
}

